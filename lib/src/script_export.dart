String _firPython(fir.RemezResult res, fx.Fixed? fixed, String name) {
  final b = StringBuffer();
  b.writeln('"""${_firTitle(res)}');
  b.writeln();
  b.writeln('Generated by $programName.  ${_note(fixed)}');
  b.writeln('"""');
  b.writeln();
  b.writeln('import numpy as np');
  b.writeln();
  b.writeln('FS = ${formatG(res.fs, precision: 17)}');
  b.writeln('TAPS = np.array([');
  for (final v in res.h) {
    b.writeln('    ${formatG(v, precision: 17)},');
  }
  b.writeln('])');
  if (fixed != null) {
    b.writeln();
    b.writeln('FRAC_BITS = ${fixed.fracBits}');
    b.writeln('# The stored integers: TAPS == TAPS_Q / 2**FRAC_BITS exactly.');
    b.writeln('TAPS_Q = np.array([${fixed.ints.join(', ')}])');
  }
  b.writeln();
  b.writeln('''

def $name(x):
    """Filter x, returning as many samples as went in.

    An FIR is a convolution, and `np.convolve` in 'full' mode returns the
    whole thing, tail included.  Trimming to len(x) is what makes this the
    same stream-oriented filter the C and RTL exports implement, with the
    (N-1)/2 samples of group delay still in it.
    """
    return np.convolve(np.asarray(x, dtype=float), TAPS)[:len(x)]


def response(points=1024):
    """Magnitude response over 0..FS/2, as (frequency, dB)."""
    w = np.linspace(0.0, np.pi, points)
    h = np.exp(-1j * np.outer(w, np.arange(TAPS.size))) @ TAPS
    return w * FS / (2 * np.pi), 20 * np.log10(np.maximum(np.abs(h), 1e-300))
''');
  return b.toString();
}

String _iirPython(iir.IIRResult res, fx.Fixed? fixed, String name) {
  final b = StringBuffer();
  b.writeln('"""${_iirTitle(res)}');
  b.writeln();
  b.writeln('Generated by $programName.  ${_note(fixed)}');
  b.writeln('"""');
  b.writeln();
  b.writeln('import numpy as np');
  b.writeln('from scipy.signal import sosfilt, sosfreqz');
  b.writeln();
  b.writeln('FS = ${formatG(res.fs, precision: 17)}');
  b.writeln('# Second-order sections, b0 b1 b2 a0 a1 a2 -- the layout scipy');
  b.writeln('# expects, and the only form that keeps this order stable.');
  b.writeln('SOS = np.array([');
  for (final s in res.sos) {
    b.writeln('    [${s.map((v) => formatG(v, precision: 17)).join(', ')}],');
  }
  b.writeln('])');
  if (fixed != null) {
    b.writeln();
    b.writeln('FRAC_BITS = ${fixed.fracBits}');
    b.writeln('SOS_Q = np.array([');
    for (var i = 0; i < res.sos.length; i++) {
      b.writeln('    [${_sectionInts(fixed, i).join(', ')}],');
    }
    b.writeln('])');
  }
  b.writeln();
  b.writeln('''

def $name(x):
    """Filter x through the cascade."""
    return sosfilt(SOS, np.asarray(x, dtype=float))


def response(points=1024):
    """Magnitude response over 0..FS/2, as (frequency, dB)."""
    w, h = sosfreqz(SOS, worN=points)
    return w * FS / (2 * np.pi), 20 * np.log10(np.maximum(np.abs(h), 1e-300))
''');
  return b.toString();
}

