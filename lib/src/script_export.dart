/// The design as a script, for the two environments most filters end up in.
///
/// Neither of these is a filter implementation to be proud of -- they call the
/// library routine and get out of the way. That is the point: what a NumPy or
/// MATLAB user wants from this program is the coefficients, in a file they can
/// run without retyping seventeen digits, and a line showing which library call
/// expects them in that shape. An FIR goes to `lfilter`/`filter` with a
/// denominator of 1; a cascade goes to `sosfilt`, which is the only form that
/// keeps a high-order design stable.
library;

import 'fir_core.dart' as fir;
import 'fixed_point.dart' as fx;
import 'format.dart';
import 'iir_core.dart' as iir;
import 'labels.dart';

/// Which language a path asks for, or null if it asks for neither.
String? scriptLanguageFor(String path) {
  final lower = path.toLowerCase();
  if (lower.endsWith('.py')) return 'python';
  if (lower.endsWith('.m')) return 'matlab';
  return null;
}

String firScript(fir.RemezResult res, String language,
        {fx.Fixed? fixed, String name = 'filter'}) =>
    language == 'matlab'
        ? _firMatlab(res, fixed, name)
        : _firPython(res, fixed, name);

String iirScript(iir.IIRResult res, String language,
        {fx.Fixed? fixed, String name = 'filter'}) =>
    language == 'matlab'
        ? _iirMatlab(res, fixed, name)
        : _iirPython(res, fixed, name);

