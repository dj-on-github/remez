String _firMatlab(fir.RemezResult res, fx.Fixed? fixed, String name) {
  final b = StringBuffer();
  b.writeln('function y = $name(x)');
  b.writeln('%$name  ${_firTitle(res)}');
  b.writeln('%');
  b.writeln('%   Generated by $programName.  ${_note(fixed)}');
  b.writeln('%   y = $name(x) filters x and returns as many samples as went');
  b.writeln('%   in, with the (N-1)/2 samples of group delay still in it.');
  b.writeln();
  b.writeln('fs = ${formatG(res.fs, precision: 17)}; %#ok<NASGU>');
  b.writeln('h = [ ...');
  for (final v in res.h) {
    b.writeln('    ${formatG(v, precision: 17)}; ...');
  }
  b.writeln('];');
  if (fixed != null) {
    b.writeln();
    b.writeln('% The stored integers: h == hq / 2^${fixed.fracBits} exactly.');
    b.writeln('fracBits = ${fixed.fracBits}; %#ok<NASGU>');
    b.writeln('hq = [${fixed.ints.join('; ')}]; %#ok<NASGU>');
  }
  b.writeln();
  b.writeln('% An FIR is a filter with a denominator of 1.');
  b.writeln('y = filter(h, 1, x);');
  b.writeln('end');
  return b.toString();
}

String _iirMatlab(iir.IIRResult res, fx.Fixed? fixed, String name) {
  final b = StringBuffer();
  b.writeln('function y = $name(x)');
  b.writeln('%$name  ${_iirTitle(res)}');
  b.writeln('%');
  b.writeln('%   Generated by $programName.  ${_note(fixed)}');
  b.writeln('%   Kept as second-order sections rather than one transfer');
  b.writeln('%   function: at this order the flattened polynomial loses its');
  b.writeln('%   roots to rounding and the filter stops being stable.');
  b.writeln();
  b.writeln('fs = ${formatG(res.fs, precision: 17)}; %#ok<NASGU>');
  b.writeln('sos = [ ...');
  for (final s in res.sos) {
    b.writeln('    ${s.map((v) => formatG(v, precision: 17)).join(', ')}; ...');
  }
  b.writeln('];');
  if (fixed != null) {
    b.writeln();
    b.writeln('fracBits = ${fixed.fracBits}; %#ok<NASGU>');
    b.writeln('sosq = [ ...');
    for (var i = 0; i < res.sos.length; i++) {
      b.writeln('    ${_sectionInts(fixed, i).join(', ')}; ...');
    }
    b.writeln(']; %#ok<NASGU>');
  }
  b.writeln();
  b.writeln('y = sosfilt(sos, x);');
  b.writeln('end');
  return b.toString();
}

// ---------------------------------------------------------------------------

String _firTitle(fir.RemezResult res) =>
    'Linear-phase FIR, type ${res.ftype} (${res.symmetry.name}), '
    'N = ${res.numtaps}';

String _iirTitle(iir.IIRResult res) =>
    '${labelOf(res.approximation)} ${res.response}, order ${res.order}, '
    '${res.sos.length} biquad(s)';

String _note(fx.Fixed? fixed) => fixed == null
    ? 'Double-precision coefficients.'
    : '${fixed.bits}-bit fixed point, ${fixed.qFormat}.';

List<int> _sectionInts(fx.Fixed fixed, int section) =>
    [for (var c = 0; c < 6; c++) fixed.ints[section * 6 + c]];
